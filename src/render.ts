/**
 * Draws every card as an SVG file and rebuilds both READMEs.
 * Run with "npm run cards" after "npm run fetch".
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Card } from './svg.ts';
import type { ThemeName } from './tokens.ts';
import { alt, building, contact, LANGS, posts, profile, show, switcher, type Lang } from './content.ts';
import { loadData, type GithubData } from './data.ts';
import { hero } from './cards/hero.ts';
import {
  aboutCard, buildingCard, buildingTitle, contactCard, experienceCard, footerCard, langPill, linkCard, postCard,
  postsTitle, projectsTitle, repoCard, stackCard,
} from './cards/sections.ts';
import { activityCard, heatmapCard, languagesCard } from './cards/stats.ts';

const THEMES: ThemeName[] = ['dark', 'light'];

/** One image in the README: where it links, how wide it is, and how to draw it. */
type Item = { name: string; width: string; href?: string; build: (lang: Lang, theme: ThemeName) => Card | null };
type Row = { items: Item[]; align?: 'right' };

export function layout(data: GithubData): Row[] {
  const full = (name: string, build: Item['build'], href?: string): Row => ({ items: [{ name, width: '100%', href, build }] });
  const rows: Row[] = [
    {
      align: 'right',
      items: LANGS.map((target) => ({
        name: `lang-${target}`,
        width: '',
        href: target === 'en' ? 'README.md' : 'README.pt-BR.md',
        build: (lang: Lang, theme: ThemeName) => langPill(lang, theme, target),
      })),
    },
    full('hero', (l, t) => hero(l, t, data), profile.linkedin),
    full('about', (l, t) => aboutCard(l, t)),
    full('experience', (l, t) => experienceCard(l, t), profile.linkedin),
    full('stack', (l, t) => stackCard(l, t)),
    full('heatmap', (l, t) => (show.heatmap ? heatmapCard(l, t, data) : null), profile.github),
    full('activity', (l, t) => (show.activity ? activityCard(l, t, data) : null)),
    full('languages', (l, t) => (show.languages ? languagesCard(l, t, data) : null)),
    full('title-building', (l, t) => buildingTitle(l, t)),
    ...building.items.map((item) => full(`building-${item.id}`, (l, t) => buildingCard(l, t, item.id))),
    full('title-projects', (l, t) => projectsTitle(l, t)),
  ];
  for (let i = 0; i < data.pinned.length; i += 3) {
    rows.push({
      items: data.pinned.slice(i, i + 3).map((repo) => ({
        name: `repo-${repo.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
        width: '33.33%',
        href: repo.url,
        build: (l: Lang, t: ThemeName) => repoCard(l, t, repo),
      })),
    });
  }
  rows.push(full('title-posts', (l, t) => postsTitle(l, t)));
  for (let i = 0; i < posts.items.length; i += 2) {
    rows.push({
      items: posts.items.slice(i, i + 2).map((post) => ({
        name: `post-${post.id}`,
        width: '50%',
        href: post.href,
        build: (l: Lang, t: ThemeName) => postCard(l, t, post.id),
      })),
    });
  }
  rows.push(
    full('contact', (l, t) => contactCard(l, t), `mailto:${profile.email}`),
    { items: contact.links.map((link) => ({ name: `link-${link.id}`, width: `${Math.round(10000 / contact.links.length) / 100}%`, href: link.href, build: (l: Lang, t: ThemeName) => linkCard(l, t, link.id) })) },
    full('footer', (l, t) => footerCard(l, t, data)),
  );
  return rows;
}

const escAttr = (s: string) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function readme(lang: Lang, rows: { row: Row; cards: Map<string, Card> }[]): string {
  const out: string[] = [
    '<!--',
    '  Generated by "npm run cards" (src/render.ts). Do not edit by hand:',
    '  change the text in src/content.ts and the look in design/tokens.json.',
    '  The cards are refreshed every day by .github/workflows/update-cards.yml.',
    '-->',
    '',
  ];
  for (const { row, cards } of rows) {
    const tags = row.items
      .filter((item) => cards.has(item.name))
      .map((item) => {
        const card = cards.get(item.name)!;
        const size = item.width ? ` width="${item.width}"` : ` height="${card.height}"`;
        const img =
          `<picture><source media="(prefers-color-scheme: dark)" srcset="./cards/dark/${lang}/${item.name}.svg"/>` +
          `<img${size} alt="${escAttr(card.label)}" src="./cards/light/${lang}/${item.name}.svg"/></picture>`;
        return item.href ? `<a href="${escAttr(item.href)}">${img}</a>` : img;
      });
    if (!tags.length) continue;
    // Cards that share a row must stay on one line with nothing between the tags.
    out.push(row.align ? `<p align="${row.align}">${tags.join('')}</p>` : tags.join(''), '');
  }
  return out.join('\n');
}

export async function renderAll(data: GithubData, root: URL) {
  const rows = layout(data);
  const cardsDir = new URL('cards/', root);
  rmSync(cardsDir, { recursive: true, force: true });
  let files = 0;
  let bytes = 0;
  for (const lang of LANGS) {
    const built: { row: Row; cards: Map<string, Card> }[] = [];
    for (const theme of THEMES) {
      const dir = new URL(`${theme}/${lang}/`, cardsDir);
      mkdirSync(dir, { recursive: true });
      for (const row of rows) {
        const cards = new Map<string, Card>();
        for (const item of row.items) {
          const card = item.build(lang, theme);
          if (!card) continue;
          const svg = await card.render();
          writeFileSync(new URL(`${item.name}.svg`, dir), svg);
          cards.set(item.name, card);
          files++;
          bytes += svg.length;
        }
        if (theme === THEMES[0]) built.push({ row, cards });
      }
    }
    writeFileSync(new URL(lang === 'en' ? 'README.md' : 'README.pt-BR.md', root), readme(lang, built));
  }
  return { files, bytes };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { files, bytes } = await renderAll(loadData(), new URL('../', import.meta.url));
  console.log(`Wrote ${files} cards (${Math.round(bytes / 1024)} KB) and 2 READMEs. Switch labels: ${Object.values(switcher).join(' / ')}. ${alt.hero.en}.`);
}
